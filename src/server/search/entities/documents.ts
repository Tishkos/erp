/**
 * Documents: invoices, payments, receipts, orders, journals, loans.
 *
 * Priority 30–59. A document is found by its number, by the reference it was
 * given by the other side (the supplier's invoice number, the bank's
 * reference), and — one tier below any hit on the record itself — by the name of
 * its party. Money is shown under the document's own grant.
 */
import { sql } from 'drizzle-orm';
import { profileHref } from '../../domain/profiles';
import type { SearchTableType } from '../types';

const supplierOf = sql`left join business_partner p on p.id = t.supplier_id`;
const customerOf = sql`left join business_partner p on p.id = t.customer_id`;

export const apInvoice: SearchTableType = {
  kind: 'table',
  key: 'ap_invoice',
  priority: 30,
  grant: { object: 'ap_invoice' },
  route: '/payables/invoices',
  table: 'ap_invoice',
  id: sql`t.id`,
  attachmentType: 'ap_invoice',
  series: ['AP_INVOICE'],
  number: sql`t.invoice_no`,
  text: [sql`t.supplier_invoice_no`],
  partyKey: sql`t.supplier_id`,
  joins: supplierOf,
  title: sql`t.supplier_invoice_no`,
  status: sql`t.status`,
  date: sql`t.invoice_date`,
  recent: sql`t.invoice_date`,
  party: sql`p.legal_name`,
  amount: { value: sql`t.total_iqd`, currency: sql`'IQD'` },
  href: (row) => profileHref('purchase_invoice', row.number),
};

