/**
 * Adds a user to a live install, shaped like one who is already there.
 *
 *   npx tsx scripts/ops/create-user.ts takwa@qs-groups.com "Takwa" --like tishko@qs-groups.com [--no-employee]
 *
 * The Users screen is the ordinary way; this is for the owner asking from a
 * terminal (2026-10-11: "make new user called takwa … permission just like
 * Tishko … send me her temporary password"). It goes through the same service
 * the screen does — `users.create`: the roles, the branches and the default
 * one, the departments, and the employee behind the account are copied from
 * the model user; the temporary password is generated by the service, printed
 * ONCE here, and is good for 72 hours (REQ-HARDEN-001 HD2: the first sign-in
 * reaches the password screen and nothing else). Nothing about the model user
 * changes.
 *
 * Super User is the one thing no service sets (it is the flag behind every
 * policy, written by the setup scripts in SQL): copied the same way, with an
 * audit row saying so. It acts as the first super user, else the first system
 * administrator — whoever may create a user.
 */
import 'dotenv/config';
import { sql } from 'drizzle-orm';
import { applyScope, db } from '../../src/server/db/client';
import * as audit from '../../src/server/services/audit';
import * as authz from '../../src/server/services/authorization';
import * as users from '../../src/server/services/users';

const args = process.argv.slice(2);
const flag = (name: string) => {
  const index = args.indexOf(`--${name}`);
  return index === -1 ? null : (args[index + 1] ?? null);
};
const positional = args.filter((value, index) => !value.startsWith('--') && !(index > 0 && args[index - 1] === '--like'));
const email = (positional[0] ?? '').trim().toLowerCase();
const displayName = (positional[1] ?? '').trim();
const like = (flag('like') ?? '').trim().toLowerCase();
const withEmployee = !args.includes('--no-employee');

if (!email.includes('@') || !displayName || !like.includes('@')) {
  console.error('usage: npx tsx scripts/ops/create-user.ts you@company.com "Your Name" --like model@company.com [--no-employee]');
  process.exit(1);
}

async function main(): Promise<void> {
  const url = process.env.DATABASE_URL ?? '';
  console.log(`database: ${url.replace(/:[^:@]*@/, ':***@') || '(unset)'}`);

  const made = await db.transaction(async (tx) => {
    const [actor] = (
      await tx.execute(sql`
        SELECT u.id, u.email
          FROM app_user u
         WHERE u.is_active
           AND (u.is_super_user OR EXISTS (SELECT 1 FROM user_role r WHERE r.user_id = u.id AND r.role_code = 'system_administrator'))
         ORDER BY u.is_super_user DESC, u.created_at
         LIMIT 1
      `)
    ).rows as { id: string; email: string }[];
    if (!actor) throw new Error('No active super user or system administrator to create the user as.');
    await applyScope(tx, { userId: actor.id, branchCode: '' });
    const principal = await authz.loadPrincipal(tx, actor.id);
    const ctx = { principal, branchCode: '' };

    const [model] = (await tx.execute(sql`select id, email, is_super_user from app_user where lower(email) = ${like} and is_active`)).rows as {
      id: string;
      email: string;
      is_super_user: boolean;
    }[];
    if (!model) throw new Error(`No active user ${like} to copy.`);

    const roleCodes = ((await tx.execute(sql`select role_code from user_role where user_id = ${model.id} order by role_code`)).rows as { role_code: string }[]).map((r) => r.role_code);
    const branches = (await tx.execute(sql`select branch_code, is_default from user_branch_scope where user_id = ${model.id} order by is_default desc, branch_code`)).rows as {
      branch_code: string;
      is_default: boolean;
    }[];
    const departmentCodes = ((await tx.execute(sql`select department_code from user_department_scope where user_id = ${model.id} order by department_code`)).rows as { department_code: string }[]).map(
      (d) => d.department_code,
    );
    const [employee] = (await tx.execute(sql`select department_code, position_code from employee where app_user_id = ${model.id}`)).rows as {
      department_code: string;
      position_code: string | null;
    }[];

    console.log(`acting as:  ${actor.email}`);
    console.log(`like:       ${model.email}${model.is_super_user ? ' (super user)' : ''}`);
    console.log(`roles:      ${roleCodes.join(', ') || '(none)'}`);
    console.log(`branches:   ${branches.map((b) => `${b.branch_code}${b.is_default ? ' (default)' : ''}`).join(', ') || '(none)'}`);
    console.log(`departments: ${departmentCodes.join(', ') || '(none)'}`);

    const created = await users.create(tx, ctx, {
      email,
      displayName,
      roleCodes,
      branchCodes: branches.map((b) => b.branch_code),
      defaultBranchCode: branches.find((b) => b.is_default)?.branch_code ?? branches[0]?.branch_code ?? null,
      departmentCodes,
      employee: withEmployee && employee ? { departmentCode: employee.department_code, positionCode: employee.position_code } : null,
    });

    if (model.is_super_user) {
      await tx.execute(sql`update app_user set is_super_user = true where id = ${created.id}`);
      await audit.record(tx, {
        actorUserId: actor.id,
        action: 'app_user.super_user_granted',
        objectType: users.PERMISSION_OBJECT,
        objectId: created.id,
        branchCode: ctx.branchCode,
        before: { isSuperUser: false },
        after: { isSuperUser: true, like: model.email, by: 'scripts/ops/create-user.ts' },
        outcome: 'success',
        requestId: null,
      });
    }
    return { ...created, superUser: model.is_super_user };
  });

  console.log('');
  console.log(`created:    ${made.email}  (${made.displayName})${made.superUser ? '  super user' : ''}`);
  console.log(`employee:   ${made.employeeNo ?? '(none)'}`);
  console.log(`temporary password (shown once, good for 72 hours; the first sign-in must replace it):`);
  console.log(`  ${made.temporaryPassword}`);
  process.exit(0);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
