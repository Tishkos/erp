import { chromium } from '@playwright/test';
const B='http://localhost:3000', OUT=process.argv[2];
const b=await chromium.launch(); const p=await b.newPage({viewport:{width:1300,height:1000}});
await p.goto(B+'/sign-in');
await p.getByRole('textbox',{name:'Email',exact:true}).fill('manager@example.com');
await p.getByLabel('Password',{exact:true}).fill('Ledger-Trial-Balance-7');
await p.getByRole('button',{name:'Sign in'}).click(); await p.waitForURL(B+'/');
await p.goto(B+'/finance/journals/JE-2026-000037',{waitUntil:'domcontentloaded',timeout:120000});
await p.waitForTimeout(2200);
await p.emulateMedia({media:'print'});
await p.pdf({path:`${OUT}/screen-print.pdf`,format:'A4'});
await p.screenshot({path:`${OUT}/screen-print.png`,fullPage:true});
console.log('printed the screen directly');
await b.close();
